"""Run confirmed fantasy newsletter jobs once, then exit.

For a deployed application run periodically via cron/systemd/cloud scheduler. Does
NOT run in the background when the local web server is closed. All sends are
idempotent by subscriber/event/week. Never set secrets in source control.

Run from repo root: uv run python app/run_digest_jobs.py
"""
from __future__ import annotations

from datetime import datetime
import hashlib
import os
from zoneinfo import ZoneInfo

from email_subscriptions import confirmed_subscribers, send_digest

ET = ZoneInfo("America/New_York")


def _lineup_text(data):
    lines = [f"Week {data.get('week')} optimal lineup (projection only)",
             f"Projected points: {data.get('projected_total', 'unavailable')}", ""]
    for slot, item in (data.get("lineup") or {}).items():
        if item:
            val = item.get("lineup_projection") or item.get("espn_projection")
            lines.append(f"{slot}: {item.get('name', 'unknown')}" + (f" · {val:.1f} projected" if isinstance(val,(int,float)) else ""))
    lines.append("\nReview lineup eligibility and ESPN lock times before kickoff. No roster was changed by this email.")
    return "\n".join(lines)


def run_due(*, now=None, engine=None, transport=None):
    """Runs at most one ready event of each kind per subscriber; no hidden retries."""
    now = now or datetime.now(ET)
    local = now.astimezone(ET)
    users = confirmed_subscribers()
    result = {"subscribers": len(users), "sent": 0, "errors": [], "claude_calls": 0}
    if not users:
        return result
    if engine is None:
        import llm as engine
        if engine.APP_CONTEXT is None:
            engine.load_app_context()
    from weekly_recap import recap_status, generate_weekly_recap
    from news_feed import roster_news
    context = engine.APP_CONTEXT or {}
    league, team = context.get("league"), context.get("team")
    if league is None or team is None:
        result["errors"].append("ESPN data unavailable")
        return result
    week = int(context.get("current_week") or getattr(league,"current_week",1))
    year = int(getattr(league,"year",2026))
    roster = context.get("roster") or []
    interested = {key: [p for p in users if p.get(key)] for key in
                  ("thursday_lineup", "monday_recap", "injury_news", "bye_alerts", "auto_swap")}

    def send(user, kind, key, subject, message):
        try:
            if send_digest(user, kind, key, subject, message, transport=transport):
                result["sent"] += 1
        except Exception as exc:
            result["errors"].append(f"{kind}: {type(exc).__name__}")

    # Thursday before first games, preferably 8 AM Eastern. Scheduler can be
    # invoked more than once and dedupe prevents duplicate emails.
    if local.weekday() == 3 and 7 <= local.hour <= 12 and interested["thursday_lineup"]:
        lineup = engine.tool_get_optimal_lineup()
        for user in interested["thursday_lineup"]:
            send(user, "thursday_lineup", f"{year}-{week}", f"Fantasy Coach · Week {week} optimal lineup", _lineup_text(lineup))

    if local.weekday() == 3 and 7 <= local.hour <= 12 and interested["bye_alerts"]:
        byes = [p.get("name") for p in roster if p.get("is_on_bye") or p.get("espn_on_bye")]
        for user in interested["bye_alerts"]:
            send(user, "bye_alerts", f"{year}-{week}", f"Week {week} bye-week check",
                 "On bye this week: " + (", ".join(byes) if byes else "None detected in your roster") +
                 "\nCheck ESPN before kickoff; game schedules and player teams can change.")

    # Once the previous week finishes, recap can be generated by exactly one
    # Claude call, cached and shared among confirmed recap subscribers.
    if interested["monday_recap"] and (local.weekday() in (0,1,2)) and local.hour >= 6:
        from email_subscriptions import was_sent
        # Try prior and current week. Do not deliver stale recaps for old weeks.
        for candidate in sorted({week, max(1,week-1)}, reverse=True):
            if all(was_sent(u["email"],"monday_recap",f"{year}-{candidate}") for u in interested["monday_recap"]):
                continue
            try:
                gate = recap_status(league, team.team_id, candidate)
                if gate.get("status") != "ready":
                    continue
                data = generate_weekly_recap(league, team.team_id, engine.client, engine.MODEL, candidate)
                if not data.get("cached"):
                    result["claude_calls"] += 1
                for user in interested["monday_recap"]:
                    send(user,"monday_recap",f"{year}-{candidate}",
                         f"Fantasy Coach · Week {candidate} final recap", data["analysis"])
                break
            except Exception as exc:
                result["errors"].append(f"recap: {type(exc).__name__}")
                break

    # Injury news: send only NEW, verified article links relevant to users'
    # injured roster players. One roster_news request is shared across readers.
    if interested["injury_news"]:
        injured = {p.get("name") for p in roster if str(p.get("injury_status") or "").upper() not in
                   ("", "ACTIVE", "NORMAL", "HEALTHY")}
        if injured:
            try:
                data = roster_news(engine.tool_get_roster().get("players") or [])
                for player in data.get("players", []):
                    if player.get("name") not in injured:
                        continue
                    stories = player.get("articles") or player.get("news") or []
                    for article in stories[:2]:
                        url = article.get("url") or article.get("link")
                        if not url or not url.startswith("https://"):
                            continue
                        key = hashlib.sha256(url.encode()).hexdigest()[:20]
                        msg = f"{player['name']}: {article.get('title', 'Injury coverage')}\n{url}\n\nCheck official status before kickoff."
                        for user in interested["injury_news"]:
                            send(user,"injury_news",key,f"Fantasy injury news · {player['name']}",msg)
            except Exception as exc:
                result["errors"].append(f"injury_news: {type(exc).__name__}")

    # Automatic ESPN changes are a *separate* double opt-in, not a side effect
    # of subscribing to emails. It requires email confirmation plus both
    # ESPN_WRITES_ENABLED and ESPN_AUTO_SWAPS_ENABLED in server configuration.
    owner_email = os.getenv("FANTASY_OWNER_EMAIL", "").strip().lower()
    authorized_auto = [u for u in interested["auto_swap"] if owner_email and u["email"] == owner_email]
    if (authorized_auto and os.getenv("ESPN_WRITES_ENABLED") == "1"
            and os.getenv("ESPN_AUTO_SWAPS_ENABLED") == "1"):
        try:
            from lineup_actions import automatic_injury_bye_lineup, create_preview, submit_preview
            from matchup_live import nfl_game_statuses
            optimal = engine.tool_get_optimal_lineup()
            restricted = automatic_injury_bye_lineup(team, optimal)
            status = nfl_game_statuses(league, week)
            preview = create_preview(league, team, restricted, game_status=status)
            if preview["changes"]:
                response = submit_preview(league, team, restricted, preview["confirmation_token"], game_status=status)
                for user in authorized_auto:
                    send(user,"auto_swap",f"{year}-{week}-{hashlib.sha256(str(response['changes']).encode()).hexdigest()[:12]}",
                         "Fantasy Coach · Automatic injury/bye lineup change",
                         "An opted-in ESPN lineup transaction was accepted. Open ESPN and verify your starting lineup.\n"+
                         "\n".join(f"{r['name']}: {r['from']} → {r['to']}" for r in response["changes"]))
        except Exception as exc:
            result["errors"].append(f"auto_swap: {type(exc).__name__}")
    return result


if __name__ == "__main__":
    result = run_due()
    # Do not print subscriber emails or credentials.
    print(f"Digest run: {result['subscribers']} subscriptions; {result['sent']} emails; "
          f"{result['claude_calls']} Claude recap calls; errors={result['errors']}")
